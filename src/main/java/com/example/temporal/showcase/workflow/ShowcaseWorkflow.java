package com.example.temporal.showcase.workflow;

import com.example.temporal.showcase.dto.ShowcaseRequest;
import com.example.temporal.showcase.dto.ShowcaseState;
import io.temporal.workflow.*;

/**
 * КОНТРАКТ РАСШИРЕННОГО ПРОЦЕССА ОБРАБОТКИ И ДОСТАВКИ ЗАКАЗА (Workflow Interface).
 *
 * Роль в системе заказов:
 * Этот интерфейс описывает координатора сложного заказа, проходящего 8 этапов (от проверки бюджета и оплаты
 * до тендера курьерских служб, отслеживания маршрута доставки и распределённой транзакции Saga).
 *
 * Точки взаимодействия с живым процессом заказа:
 * 1) @WorkflowMethod — запустить полный цикл обработки заказа.
 * 2) Три канала связи с заказом во время его выполнения:
 *    - @SignalMethod (Асинхронный сигнал: например, оператор нажал кнопку "Подтверждаю заказ").
 *    - @QueryMethod  (Запрос состояния: прочитать текущий этап, бюджет и лог заказа без вмешательства в его работу).
 *    - @UpdateMethod + @UpdateValidatorMethod (Синхронное изменение бюджета заказа на ходу с предварительной валидацией).
 */
@WorkflowInterface
public interface ShowcaseWorkflow {

    /**
     * Имя очереди заявок (Task Queue) на сервере Temporal,
     * через которую процесс заказа и его внешние операции (Activities) получают задачи.
     */
    String TASK_QUEUE = "ShowcaseTaskQueue";

    /**
     * 1. СТАРТ ПОЛНОГО ЦИКЛА ЗАКАЗА (@WorkflowMethod).
     *
     * Запускает прохождение всех этапов заказа (Этапы 0..7) и возвращает итоговую карточку состояния ShowcaseState.
     */
    @WorkflowMethod
    ShowcaseState runShowcase(ShowcaseRequest request);

    /**
     * 2. УВЕДОМЛЕНИЕ О ПОДТВЕРЖДЕНИИ ЗАКАЗА (@SignalMethod — Асинхронный сигнал в один конец).
     *
     * Как работает:
     * Отправитель передаёт подтверждение заказа и не ждёт ответа (метод возвращает `void`),
     * а внутри процесса заказа флаг `approvedBySignal` сразу переключается в `true`.
     *
     * Ожидаемое поведение:
     * Если заказ находился на Шаге 2 в ожидании подтверждения (`Workflow.await`),
     * он мгновенно просыпается (не дожидаясь истечения таймера) и переходит к следующему этапу.
     */
    @SignalMethod
    void approveSignal(String approverName);

    /**
     * 3. ЗАПРОС ТЕКУЩЕГО СОСТОЯНИЯ ЗАКАЗА (@QueryMethod — Только чтение).
     *
     * Как работает:
     * Мгновенно возвращает карточку текущего состояния заказа (этап, бюджет, выбранную службу доставки, журнал шагов).
     * Не изменяет состояние заказа, не будит таймеры и не добавляет событий в журнал Event History.
     * Работает как для активных, так и для уже завершённых заказов.
     */
    @QueryMethod
    ShowcaseState getState();

    /**
     * 4. СИНХРОННОЕ ИЗМЕНЕНИЕ БЮДЖЕТА ЗАКАЗА (@UpdateMethod).
     *
     * Как работает:
     * В отличие от @SignalMethod, вызывающая сторона изменяет бюджет заказа на величину `delta`
     * (например, +250 или -100) и синхронно дожидается ответа с новой суммой бюджета.
     *
     * Ожидаемое поведение:
     * Сначала автоматически вызывается метод-валидатор `validateBudgetUpdate`. Если проверка пройдена,
     * бюджет заказа обновляется, изменение фиксируется в Event History, а клиенту возвращается обновлённая сумма.
     */
    @UpdateMethod
    double adjustBudgetUpdate(double delta);

    /**
     * 5. ВАЛИДАТОР ИЗМЕНЕНИЯ БЮДЖЕТА ЗАКАЗА (@UpdateValidatorMethod).
     *
     * Зачем нужен:
     * Связан с методом `adjustBudgetUpdate` через `updateName = "adjustBudgetUpdate"`.
     * Выполняется ДО того, как изменение попадёт в историю событий заказа.
     *
     * Ожидаемое поведение:
     * Если при текущем бюджете $1000 приходит запрос на уменьшение на $5000 (`delta = -5000`),
     * валидатор выбрасывает `IllegalArgumentException`. Запрос сразу отклоняется с ошибкой,
     * а состояние заказа и его Event History остаются нетронутыми.
     */
    @UpdateValidatorMethod(updateName = "adjustBudgetUpdate")
    void validateBudgetUpdate(double delta);
}
